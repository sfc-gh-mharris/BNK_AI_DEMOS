-------------------------------------------------------------------------------
-- CLIENTS
-- Master table of all banking clients subject to KYC obligations.
-- Source: Core Banking System (CBS) client onboarding feed.
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.KYC_AML.CLIENTS (
    client_id       VARCHAR(36)   NOT NULL
        COMMENT 'Universally unique identifier for the client record. Format: UUID v4. Generated by the Core Banking System at onboarding.',
    entity_type     VARCHAR(20)   NOT NULL
        COMMENT 'Legal entity classification. Values: Individual (natural person) or Corporate (legal entity). Drives CDD vs. corporate due diligence workflows.',
    first_name      VARCHAR(100)
        COMMENT 'Given name of an individual client. NULL for Corporate entities. Sourced from government-issued identity document at onboarding.',
    last_name       VARCHAR(100)
        COMMENT 'Family name / surname of an individual client. NULL for Corporate entities. Sourced from government-issued identity document at onboarding.',
    company_name    VARCHAR(255)
        COMMENT 'Registered legal name of a corporate client. NULL for Individual entities. Sourced from corporate registry filing.',
    nationality     VARCHAR(3)
        COMMENT 'ISO 3166-1 alpha-3 country code representing the client nationality (individuals) or country of incorporation (corporates).',
    country_of_residence VARCHAR(3)
        COMMENT 'ISO 3166-1 alpha-3 country code of the client primary residential address (individuals) or registered office (corporates).',
    risk_rating     VARCHAR(20)   NOT NULL
        COMMENT 'Composite KYC risk rating assigned by the Risk Assessment Engine. Values: Low, Medium, High, PEP (Politically Exposed Person), Sanctioned. Reviewed at minimum annually.',
    onboarding_date DATE          NOT NULL
        COMMENT 'Date the client relationship was formally established and initial CDD completed. Format: YYYY-MM-DD.',
    relationship_manager VARCHAR(100)
        COMMENT 'Full name of the assigned Relationship Manager responsible for ongoing client oversight. Sourced from HR/CRM system.',
    status          VARCHAR(20)   NOT NULL
        COMMENT 'Current lifecycle status of the client relationship. Values: Active (normal operations), UnderReview (pending KYC refresh), Restricted (limited services), Exited (relationship terminated).',

    CONSTRAINT pk_clients PRIMARY KEY (client_id)
)
COMMENT = 'Master client registry for KYC/AML compliance. Contains all natural persons and legal entities with an active or historical banking relationship. Fed by Core Banking System; risk ratings updated by the Risk Assessment Engine.';

-------------------------------------------------------------------------------
-- KYC_CASES
-- Each KYC review event (new client onboarding, periodic review, trigger event)
-- is tracked as a case with workflow state.
-- Source: KYC Case Management System (KCMS).
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.KYC_AML.KYC_CASES (
    case_id         VARCHAR(36)   NOT NULL
        COMMENT 'Universally unique identifier for the KYC case. Format: UUID v4. Generated by the KYC Case Management System (KCMS).',
    client_id       VARCHAR(36)   NOT NULL
        COMMENT 'Foreign key to CLIENTS.client_id. Identifies the client under review in this case.',
    case_type       VARCHAR(30)   NOT NULL
        COMMENT 'Classification of the KYC review trigger. Values: NewClient (initial onboarding), PeriodicReview (scheduled refresh per risk tier), TriggerEvent (adverse media, sanctions hit), EnhancedDueDiligence (elevated risk requiring deeper review).',
    status          VARCHAR(20)   NOT NULL
        COMMENT 'Current workflow state of the case. Values: Open, InReview, PendingDocuments, Approved, Rejected, Escalated. State transitions governed by KCMS workflow engine.',
    priority        VARCHAR(10)   NOT NULL
        COMMENT 'Urgency classification determining SLA. Values: Low (30-day SLA), Medium (14-day), High (7-day), Critical (24-hour). Auto-assigned based on client risk rating and case type.',
    assigned_analyst VARCHAR(100)
        COMMENT 'Full name of the KYC analyst currently responsible for the case. NULL if unassigned. Sourced from KCMS work queue assignment.',
    opened_date     DATE          NOT NULL
        COMMENT 'Date the case was created in KCMS. Format: YYYY-MM-DD.',
    due_date        DATE
        COMMENT 'SLA deadline for case resolution. Calculated from opened_date plus SLA days based on priority. NULL only for cases created before SLA tracking was implemented.',
    closed_date     DATE
        COMMENT 'Date the case reached a terminal state (Approved, Rejected). NULL for open cases.',
    notes           VARCHAR(2000)
        COMMENT 'Free-text analyst notes and observations. May contain references to external communications or escalation reasons.',

    CONSTRAINT pk_kyc_cases PRIMARY KEY (case_id),
    CONSTRAINT fk_cases_client FOREIGN KEY (client_id) REFERENCES BNK.KYC_AML.CLIENTS(client_id)
)
COMMENT = 'KYC case tracking table. Each row represents a single review event in the client lifecycle — from initial onboarding through periodic reviews and trigger-based investigations. Sourced from the KYC Case Management System (KCMS).';

-------------------------------------------------------------------------------
-- DOCUMENTS_METADATA
-- Catalog of all documents uploaded for KYC verification.
-- Physical files reside in stage @BNK.KYC_AML.KYC_DOCUMENTS.
-- Source: Document Management System (DMS) upload events.
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.KYC_AML.DOCUMENTS_METADATA (
    doc_id          VARCHAR(36)   NOT NULL
        COMMENT 'Universally unique identifier for the document record. Format: UUID v4. Generated by the Document Management System at upload.',
    case_id         VARCHAR(36)   NOT NULL
        COMMENT 'Foreign key to KYC_CASES.case_id. Links the document to the specific KYC case it was submitted for.',
    client_id       VARCHAR(36)   NOT NULL
        COMMENT 'Foreign key to CLIENTS.client_id. Denormalized for query performance — identifies the document owner.',
    doc_type        VARCHAR(30)   NOT NULL
        COMMENT 'Declared document category at time of upload. Values: Passport, DriversLicense, NationalID, FinancialStatement, UtilityBill, CorporateRegistry, BeneficialOwnership. May be corrected by AI_CLASSIFY post-processing.',
    file_path       VARCHAR(500)  NOT NULL
        COMMENT 'Relative path within the @BNK.KYC_AML.KYC_DOCUMENTS stage. Convention: clients/<client_id>/<doc_type>_<doc_id>.pdf',
    upload_date     TIMESTAMP_NTZ NOT NULL
        COMMENT 'UTC timestamp when the document was uploaded to the stage. Sourced from DMS upload event metadata.',
    file_size_bytes INTEGER
        COMMENT 'Size of the uploaded file in bytes. Used for processing cost estimation and anomaly detection (e.g., unusually small passport scans).',
    extraction_status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        COMMENT 'AI processing pipeline state. Values: Pending (awaiting processing), Processing (AI_PARSE_DOCUMENT in progress), Completed (extraction successful), Failed (extraction error — requires manual review).',
    classification_confidence FLOAT
        COMMENT 'Confidence score (0.0–1.0) from AI_CLASSIFY for the predicted document type. NULL until processing completes. Values below 0.85 trigger manual review.',

    CONSTRAINT pk_documents PRIMARY KEY (doc_id),
    CONSTRAINT fk_docs_case FOREIGN KEY (case_id) REFERENCES BNK.KYC_AML.KYC_CASES(case_id),
    CONSTRAINT fk_docs_client FOREIGN KEY (client_id) REFERENCES BNK.KYC_AML.CLIENTS(client_id)
)
COMMENT = 'Document metadata catalog for all files submitted during KYC reviews. Tracks upload status, AI processing state, and links to physical files on the KYC_DOCUMENTS stage. One row per uploaded document.';

-------------------------------------------------------------------------------
-- VERIFICATION_RESULTS
-- Output of the AI extraction and identity cross-referencing pipeline.
-- One result per processed document.
-- Source: AI processing pipeline (PROCESS_KYC_DOCUMENT procedure).
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.KYC_AML.VERIFICATION_RESULTS (
    result_id       VARCHAR(36)   NOT NULL
        COMMENT 'Universally unique identifier for the verification result. Format: UUID v4. Generated by the AI processing pipeline upon completion.',
    doc_id          VARCHAR(36)   NOT NULL
        COMMENT 'Foreign key to DOCUMENTS_METADATA.doc_id. Identifies the source document that produced this verification result.',
    extracted_fields VARIANT      NOT NULL
        COMMENT 'Semi-structured JSON containing all fields extracted by AI_EXTRACT. Schema varies by doc_type. Common keys: full_name, date_of_birth, document_number, issuing_authority, expiry_date, address.',
    confidence_score FLOAT        NOT NULL
        COMMENT 'Overall extraction confidence (0.0–1.0). Weighted average across all extracted fields. Scores below 0.80 trigger manual analyst review.',
    ai_classification VARCHAR(30)
        COMMENT 'Document type as predicted by AI_CLASSIFY. May differ from DOCUMENTS_METADATA.doc_type if the upload was mislabeled.',
    verified_by     VARCHAR(100)  NOT NULL
        COMMENT 'Identity of the verification actor. Values: SYSTEM (automated AI pipeline), or analyst full name (manual review). Tracks accountability for audit trail.',
    verification_date TIMESTAMP_NTZ NOT NULL
        COMMENT 'UTC timestamp when the verification was completed (automated or manual).',
    match_status    VARCHAR(30)   NOT NULL
        COMMENT 'Result of cross-referencing extracted fields against client master data. Values: Match (all fields align), Mismatch (critical field discrepancy), Partial (minor discrepancy — e.g., name transliteration), ManualReviewRequired (confidence too low for automated decision).',

    CONSTRAINT pk_verification PRIMARY KEY (result_id),
    CONSTRAINT fk_verify_doc FOREIGN KEY (doc_id) REFERENCES BNK.KYC_AML.DOCUMENTS_METADATA(doc_id)
)
COMMENT = 'AI-generated verification results from the document processing pipeline. Stores extracted field data (as VARIANT), classification output, confidence scores, and match status against client master data. Audit-critical — supports regulatory evidence requirements.';

-------------------------------------------------------------------------------
-- KYC_POLICIES
-- Compliance policy reference data. Full-text policy content supports
-- Cortex Search for RAG-based policy lookup by the KYC Agent.
-- Source: Compliance Policy Management System (CPMS).
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.KYC_AML.KYC_POLICIES (
    policy_id       VARCHAR(20)   NOT NULL
        COMMENT 'Unique policy identifier. Format: POL-<category_code>-<sequence>. Assigned by the Compliance Policy Management System.',
    title           VARCHAR(255)  NOT NULL
        COMMENT 'Human-readable policy title. Used as the primary display label in search results and agent citations.',
    jurisdiction    VARCHAR(10)   NOT NULL
        COMMENT 'Regulatory jurisdiction to which the policy applies. Values: US, UK, EU, APAC, Global. A policy may be superseded by jurisdiction-specific variants.',
    category        VARCHAR(30)   NOT NULL
        COMMENT 'Policy domain classification. Values: CDD (Customer Due Diligence), EDD (Enhanced Due Diligence), PEP (Politically Exposed Persons), Sanctions, BeneficialOwnership, OngoingMonitoring.',
    effective_date  DATE          NOT NULL
        COMMENT 'Date from which this policy version is enforceable. Used to determine which version applies to a given case based on case opened_date.',
    content         VARCHAR(16000) NOT NULL
        COMMENT 'Full text of the compliance policy. Multi-paragraph prose describing requirements, procedures, and escalation paths. Indexed by Cortex Search for RAG retrieval.',

    CONSTRAINT pk_policies PRIMARY KEY (policy_id)
)
COMMENT = 'KYC/AML compliance policy reference library. Contains full-text policies across jurisdictions and categories (CDD, EDD, PEP, Sanctions, Beneficial Ownership, Ongoing Monitoring). Indexed by Cortex Search Service for RAG-based policy retrieval by the KYC Agent.';

-------------------------------------------------------------------------------
-- ALERT_QUEUE
-- Real-time alert feed for KYC/AML events requiring analyst attention.
-- Source: Transaction Monitoring System (TMS) and Screening Engine.
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.KYC_AML.ALERT_QUEUE (
    alert_id        VARCHAR(36)   NOT NULL
        COMMENT 'Universally unique identifier for the alert. Format: UUID v4. Generated by the source system (TMS or Screening Engine).',
    client_id       VARCHAR(36)   NOT NULL
        COMMENT 'Foreign key to CLIENTS.client_id. Identifies the client associated with this alert.',
    alert_type      VARCHAR(30)   NOT NULL
        COMMENT 'Classification of the alert trigger. Values: SanctionsHit (name match on sanctions list), AdverseMedia (negative news detected), UnusualActivity (transaction pattern anomaly), DocumentExpiry (ID document nearing expiration), RiskRatingChange (external risk score movement).',
    severity        VARCHAR(10)   NOT NULL
        COMMENT 'Alert urgency level determining response SLA. Values: Low (5-day response), Medium (48-hour), High (24-hour), Critical (4-hour — immediate escalation).',
    created_date    TIMESTAMP_NTZ NOT NULL
        COMMENT 'UTC timestamp when the alert was generated by the source system.',
    status          VARCHAR(20)   NOT NULL
        COMMENT 'Alert lifecycle state. Values: New (unacknowledged), Assigned (analyst picked up), Investigating (active review), Resolved (legitimate activity confirmed), FalsePositive (no actual risk identified).',
    assigned_to     VARCHAR(100)
        COMMENT 'Full name of the analyst assigned to investigate this alert. NULL for unassigned (New status) alerts.',

    CONSTRAINT pk_alerts PRIMARY KEY (alert_id),
    CONSTRAINT fk_alerts_client FOREIGN KEY (client_id) REFERENCES BNK.KYC_AML.CLIENTS(client_id)
)
COMMENT = 'Real-time alert queue for KYC/AML events. Fed by the Transaction Monitoring System (sanctions screening, adverse media, unusual activity) and internal triggers (document expiry, risk rating changes). Analysts work this queue in priority order.';
