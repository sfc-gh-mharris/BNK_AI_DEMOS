USE DATABASE BNK;
USE SCHEMA CUSTOMER_360;
USE WAREHOUSE BNK_WH;

-------------------------------------------------------------------------------
-- CUSTOMERS
-- Source: Core banking system (CBS) customer master extract
-- Grain: One row per retail/commercial banking customer
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.CUSTOMER_360.CUSTOMERS (
    customer_id     VARCHAR(36)     NOT NULL
        COMMENT 'Universally unique identifier for each customer, generated as UUID v4. Primary key referenced by ACCOUNTS, INTERACTIONS, CUSTOMER_NOTES, and OFFERS.',
    first_name      VARCHAR(100)    NOT NULL
        COMMENT 'Customer legal first name as registered in the core banking system (CBS). Used for personalization and identity verification.',
    last_name       VARCHAR(100)    NOT NULL
        COMMENT 'Customer legal last name as registered in CBS. Combined with first_name for display and search.',
    email           VARCHAR(255)
        COMMENT 'Primary email address on file. Used for digital communications, offer delivery, and account recovery. May be NULL for branch-only customers.',
    segment         VARCHAR(20)     NOT NULL
        COMMENT 'Customer business segment classification. Values: Consumer (retail individuals), SmallBusiness (annual revenue < $5M), Commercial (annual revenue >= $5M). Assigned by relationship management team.',
    region          VARCHAR(20)     NOT NULL
        COMMENT 'Geographic region based on primary mailing address. Values: Northeast, Southeast, Midwest, West, Southwest. Used for regional performance reporting and branch allocation.',
    tenure_months   INTEGER         NOT NULL
        COMMENT 'Number of months since the customer first opened any account with the bank. Calculated as DATEDIFF(month, created_date, CURRENT_DATE). Key driver of retention models.',
    lifetime_value  NUMBER(12,2)    NOT NULL
        COMMENT 'Estimated total net revenue generated by this customer over their relationship lifetime, in USD. Calculated quarterly by the analytics team using fee income + net interest margin - servicing cost.',
    created_date    DATE            NOT NULL
        COMMENT 'Date the customer record was first created in CBS, representing the start of the banking relationship.',
    status          VARCHAR(10)     NOT NULL
        COMMENT 'Current relationship status. Values: Active (at least one open account), Inactive (no activity in 12+ months but accounts open), Closed (all accounts closed). Updated nightly by batch process.',
    
    CONSTRAINT pk_customers PRIMARY KEY (customer_id)
)
COMMENT = 'Master customer dimension table sourced from Core Banking System (CBS). Contains demographic, segmentation, and relationship attributes for all retail and commercial banking customers. Updated nightly via CDC from CBS.'
;

-------------------------------------------------------------------------------
-- ACCOUNTS
-- Source: Core banking system (CBS) account master
-- Grain: One row per banking account (a customer may hold multiple)
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.CUSTOMER_360.ACCOUNTS (
    account_id      VARCHAR(36)     NOT NULL
        COMMENT 'Universally unique identifier for each account. Primary key. Format: UUID v4.',
    customer_id     VARCHAR(36)     NOT NULL
        COMMENT 'Foreign key to CUSTOMERS.customer_id. Identifies the account holder. A customer may have multiple accounts across product types.',
    product_type    VARCHAR(20)     NOT NULL
        COMMENT 'Banking product classification. Values: Checking, Savings, CreditCard, MoneyMarket, CD (Certificate of Deposit), Investment. Drives fee schedule and interest rate logic.',
    balance         NUMBER(14,2)    NOT NULL
        COMMENT 'Current account balance in USD as of the last end-of-day processing. For credit cards, represents outstanding balance owed. For deposit accounts, represents available funds.',
    opened_date     DATE            NOT NULL
        COMMENT 'Date the account was originally opened. Used for tenure calculation and regulatory reporting (CRA).',
    status          VARCHAR(10)     NOT NULL
        COMMENT 'Current account status. Values: Active (normal operations), Dormant (no activity 6+ months), Closed (permanently closed), Frozen (hold placed by compliance/fraud). Updated by nightly batch.',
    interest_rate   NUMBER(5,4)
        COMMENT 'Current annual interest rate applied to the account as a decimal (e.g., 0.0425 = 4.25% APY). NULL for checking accounts with no interest. Set by Treasury based on Fed Funds rate + spread.',
    
    CONSTRAINT pk_accounts PRIMARY KEY (account_id)
)
COMMENT = 'Account-level detail from Core Banking System (CBS). Each row represents a single banking product held by a customer. Balances reflect end-of-day position. Updated nightly via CDC.'
;

-------------------------------------------------------------------------------
-- TRANSACTIONS
-- Source: Transaction processing system (TPS) / card network feeds
-- Grain: One row per financial transaction
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.CUSTOMER_360.TRANSACTIONS (
    txn_id          VARCHAR(36)     NOT NULL
        COMMENT 'Universally unique identifier for each transaction. Primary key. Generated by the transaction processing system at time of authorization.',
    account_id      VARCHAR(36)     NOT NULL
        COMMENT 'Foreign key to ACCOUNTS.account_id. Identifies which account was debited or credited.',
    txn_date        DATE            NOT NULL
        COMMENT 'Settlement date of the transaction (not authorization date). Used for statement generation and regulatory reporting.',
    amount          NUMBER(12,2)    NOT NULL
        COMMENT 'Transaction amount in USD. Positive values = credits/deposits. Negative values = debits/purchases/withdrawals. Absolute value used for volume reporting.',
    category        VARCHAR(20)     NOT NULL
        COMMENT 'Merchant category classification. Values: Groceries, Dining, Travel, Entertainment, Utilities, Transfer, Deposit, Withdrawal, Payment. Derived from MCC codes for card transactions.',
    merchant_name   VARCHAR(200)
        COMMENT 'Name of the merchant or counterparty as reported by the card network or ACH originator. NULL for internal transfers and ATM withdrawals.',
    channel         VARCHAR(10)     NOT NULL
        COMMENT 'Channel through which the transaction was initiated. Values: Branch (teller), ATM, Online (web banking), Mobile (app), Wire (wire transfer desk). Used for channel mix analysis.',
    
    CONSTRAINT pk_transactions PRIMARY KEY (txn_id)
)
COMMENT = 'Financial transaction detail sourced from Transaction Processing System (TPS) and card network settlement files. Contains all debits and credits across all account types. Loaded daily after end-of-day settlement.'
;

-------------------------------------------------------------------------------
-- INTERACTIONS
-- Source: CRM system (Salesforce Service Cloud) + digital channel logs
-- Grain: One row per customer service interaction
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.CUSTOMER_360.INTERACTIONS (
    interaction_id      VARCHAR(36)     NOT NULL
        COMMENT 'Universally unique identifier for each interaction. Primary key. Generated by CRM at case creation.',
    customer_id         VARCHAR(36)     NOT NULL
        COMMENT 'Foreign key to CUSTOMERS.customer_id. Identifies the customer who initiated or was the subject of this interaction.',
    channel             VARCHAR(20)     NOT NULL
        COMMENT 'Service channel used. Values: Branch (in-person), CallCenter (phone), Email, Chat (digital chat widget), Mobile (in-app messaging). Drives staffing models and cost-to-serve analysis.',
    interaction_date    DATE            NOT NULL
        COMMENT 'Date the interaction occurred or the case was opened. For multi-day cases, reflects the initial contact date.',
    topic               VARCHAR(30)     NOT NULL
        COMMENT 'Primary topic classification assigned by the agent or auto-classifier. Values: AccountInquiry, FeeDispute, ProductInquiry, Complaint, ServiceRequest. Used for root cause analysis.',
    sentiment           VARCHAR(10)     NOT NULL
        COMMENT 'Customer sentiment detected during the interaction. Values: Positive, Neutral, Negative. Determined by NLP model for digital channels or agent assessment for voice/branch.',
    resolution_status   VARCHAR(20)     NOT NULL
        COMMENT 'Outcome of the interaction. Values: Resolved, Pending, Escalated, Transferred. Drives first-contact-resolution (FCR) metrics.',
    agent_name          VARCHAR(100)    NOT NULL
        COMMENT 'Full name of the bank employee who handled this interaction. Used for agent performance tracking and coaching.',
    notes               TEXT
        COMMENT 'Free-text summary of the interaction written by the handling agent. Contains context about the customer issue, actions taken, and any follow-up commitments. Used for continuity across interactions.',
    
    CONSTRAINT pk_interactions PRIMARY KEY (interaction_id)
)
COMMENT = 'Customer service interaction history from CRM (Salesforce Service Cloud) and digital channel platforms. Tracks every touchpoint across all service channels with sentiment and resolution data. Updated in near-real-time via streaming CDC.'
;

-------------------------------------------------------------------------------
-- PRODUCTS
-- Source: Product management system / Treasury
-- Grain: One row per banking product offering
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.CUSTOMER_360.PRODUCTS (
    product_id          VARCHAR(36)     NOT NULL
        COMMENT 'Unique identifier for each banking product. Primary key. Assigned by product management team.',
    name                VARCHAR(100)    NOT NULL
        COMMENT 'Marketing name of the product as displayed to customers (e.g., "Premier Checking", "High-Yield Savings"). Must match brand guidelines.',
    category            VARCHAR(20)     NOT NULL
        COMMENT 'Product family grouping. Values: Checking, Savings, CreditCard, MoneyMarket, CD, Investment. Aligns with ACCOUNTS.product_type.',
    annual_fee          NUMBER(8,2)     NOT NULL
        COMMENT 'Annual fee charged for this product in USD. Zero for fee-free products. May be waived based on balance thresholds defined in fee schedule.',
    interest_rate_range VARCHAR(30)
        COMMENT 'Display string showing the APY range for this product (e.g., "0.50% - 4.25% APY"). Actual rate depends on balance tier and market conditions. NULL for non-interest products.',
    description         TEXT            NOT NULL
        COMMENT 'Full marketing description of the product including key features, eligibility requirements, and value proposition. Used in product recommendation engines and advisor tools.',
    
    CONSTRAINT pk_products PRIMARY KEY (product_id)
)
COMMENT = 'Product catalog maintained by the Product Management team. Contains all currently offered and recently retired banking products with pricing and feature details. Updated manually when products launch or change.'
;

-------------------------------------------------------------------------------
-- OFFERS
-- Source: Marketing automation platform (campaign management)
-- Grain: One row per personalized offer sent to a customer
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.CUSTOMER_360.OFFERS (
    offer_id        VARCHAR(36)     NOT NULL
        COMMENT 'Universally unique identifier for each offer instance. Primary key. Generated by the campaign management system at send time.',
    customer_id     VARCHAR(36)     NOT NULL
        COMMENT 'Foreign key to CUSTOMERS.customer_id. The customer this offer was targeted to.',
    product_id      VARCHAR(36)     NOT NULL
        COMMENT 'Foreign key to PRODUCTS.product_id. The product being recommended in this offer.',
    offer_type      VARCHAR(20)     NOT NULL
        COMMENT 'Strategic intent of the offer. Values: CrossSell (new product to existing customer), Upsell (upgrade existing product), Retention (prevent attrition), WinBack (re-engage churned customer).',
    status          VARCHAR(10)     NOT NULL
        COMMENT 'Current funnel stage of the offer. Values: Sent (delivered), Viewed (opened/displayed), Clicked (CTA engaged), Converted (product opened), Expired (past expiry with no action). Updated by event stream.',
    sent_date       DATE            NOT NULL
        COMMENT 'Date the offer was delivered to the customer via their preferred channel. Used for time-to-conversion analysis and offer fatigue calculations.',
    expires_date    DATE            NOT NULL
        COMMENT 'Date after which the offer is no longer valid. Typically 30-90 days after sent_date depending on offer_type. Used for urgency messaging and cleanup.',
    
    CONSTRAINT pk_offers PRIMARY KEY (offer_id)
)
COMMENT = 'Personalized offer history from the marketing automation platform. Tracks the full lifecycle of each offer from send through conversion or expiry. Used for next-best-action modeling and campaign ROI analysis.'
;

-------------------------------------------------------------------------------
-- CUSTOMER_NOTES
-- Source: Relationship management portal / advisor workstation
-- Grain: One row per note entry (chunked for Cortex Search indexing)
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.CUSTOMER_360.CUSTOMER_NOTES (
    note_id         VARCHAR(36)     NOT NULL
        COMMENT 'Universally unique identifier for each note. Primary key. Generated at note creation in the advisor workstation.',
    customer_id     VARCHAR(36)     NOT NULL
        COMMENT 'Foreign key to CUSTOMERS.customer_id. Identifies which customer this note pertains to.',
    agent_name      VARCHAR(100)    NOT NULL
        COMMENT 'Full name of the relationship manager or advisor who authored this note. Used for attribution and search filtering.',
    note_date       DATE            NOT NULL
        COMMENT 'Date the note was created. Used for chronological ordering of customer interaction history.',
    note_text       TEXT            NOT NULL
        COMMENT 'Free-form text content of the advisor note. Contains interaction summaries, customer preferences, follow-up items, and relationship context. Indexed by Cortex Search for semantic retrieval.',
    
    CONSTRAINT pk_customer_notes PRIMARY KEY (note_id)
)
COMMENT = 'Unstructured advisor notes from the Relationship Management portal. Each note captures qualitative context about customer interactions, preferences, and follow-up commitments. Indexed by CUSTOMER_NOTES_SEARCH Cortex Search Service for semantic retrieval by the Customer 360 Agent.'
;

-------------------------------------------------------------------------------
-- POLICIES
-- Source: Legal/Compliance document management system
-- Grain: One row per policy document
-------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS BNK.CUSTOMER_360.POLICIES (
    policy_id       VARCHAR(36)     NOT NULL
        COMMENT 'Unique identifier for each policy document. Primary key. Assigned by the compliance document management system.',
    title           VARCHAR(200)    NOT NULL
        COMMENT 'Official title of the policy document (e.g., "Overdraft Fee Waiver Policy"). Used as display label and search attribute.',
    category        VARCHAR(20)     NOT NULL
        COMMENT 'Policy domain classification. Values: Fees, Disputes, Privacy, Compliance, Products, Operations. Used for filtering in search and governance reporting.',
    effective_date  DATE            NOT NULL
        COMMENT 'Date this version of the policy became effective. Newer effective_date supersedes prior versions with the same title.',
    content         TEXT            NOT NULL
        COMMENT 'Full text of the policy document including scope, definitions, procedures, and exceptions. Indexed by Cortex Search for semantic retrieval by advisors and the Customer 360 Agent.',
    
    CONSTRAINT pk_policies PRIMARY KEY (policy_id)
)
COMMENT = 'Bank policy document repository sourced from the Legal/Compliance document management system. Contains full-text policies governing fees, disputes, privacy, compliance, products, and operations. Indexed by POLICY_SEARCH Cortex Search Service for RAG-based retrieval.'
;
